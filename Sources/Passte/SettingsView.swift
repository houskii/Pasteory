import AppKit
import Carbon
import PassteCore
import ServiceManagement
import SwiftUI

struct SettingsView: View {
    @ObservedObject var state: AppState
    @ObservedObject var settings: AppSettings
    let pasteCoordinator: PasteCoordinator
    let onShortcutChange: () -> Void
    let onExport: () -> Void
    let onImport: () -> Void
    @State private var selectedTab = "general"
    @State private var excludedBundle = ""
    @State private var loginEnabled = SMAppService.mainApp.status == .enabled
    @State private var shortcutError: String?

    var body: some View {
        TabView(selection: $selectedTab) {
            general.tabItem { Label("通用", systemImage: "gearshape") }.tag("general")
            privacy.tabItem { Label("采集与隐私", systemImage: "hand.raised") }.tag("privacy")
            shortcuts.tabItem { Label("快捷键", systemImage: "command") }.tag("shortcuts")
            storage.tabItem { Label("存储与清理", systemImage: "externaldrive") }.tag("storage")
            advanced.tabItem { Label("高级诊断", systemImage: "stethoscope") }.tag("advanced")
            about.tabItem { Label("关于", systemImage: "info.circle") }.tag("about")
        }
        .frame(width: 680, height: 500)
        .padding(20)
        .tint(.purple)
    }

    private var general: some View {
        Form {
            Section("运行") {
                Toggle("登录时启动 Passte", isOn: Binding(get: { loginEnabled }, set: { enabled in updateLoginItem(enabled) }))
            }
            Section("状态") {
                LabeledContent("运行形态", value: "仅菜单栏")
                LabeledContent("数据位置", value: "~/Library/Application Support/Passte")
            }
        }.formStyle(.grouped)
    }

    private var privacy: some View {
        Form {
            Section("剪贴板检测") {
                Picker("检测频率", selection: $settings.clipboardPollingInterval) {
                    ForEach(ClipboardPollingInterval.allCases) { interval in
                        Text(interval.title).tag(interval)
                    }
                }
                .pickerStyle(.segmented)
                Text("默认每 1 秒检查一次。频率修改后会在下一轮检测生效；休眠和锁屏时停止检测。")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            }
            Section("默认保护") {
                Label("自动忽略“钥匙串访问”和“密码”应用", systemImage: "lock.shield")
                Label("自动忽略 Concealed、Transient 和 AutoGenerated 内容", systemImage: "eye.slash")
                Label("单项内容上限为 10 MB", systemImage: "gauge.with.dots.needle.33percent")
            }
            Section("排除应用的 Bundle ID") {
                ForEach(settings.excludedBundleIdentifiers.sorted(), id: \.self) { bundle in
                    HStack { Text(bundle); Spacer(); Button("移除") { settings.excludedBundleIdentifiers.remove(bundle) } }
                }
                HStack {
                    TextField("例如 com.example.SecretApp", text: $excludedBundle)
                    Button("添加") {
                        let value = excludedBundle.trimmingCharacters(in: .whitespacesAndNewlines)
                        if !value.isEmpty { settings.excludedBundleIdentifiers.insert(value); excludedBundle = "" }
                    }
                }
            }
        }.formStyle(.grouped)
    }

    private var shortcuts: some View {
        Form {
            Section("打开快捷面板") {
                ShortcutRecorder(keyCode: settings.shortcutKeyCode, modifiers: settings.shortcutModifiers) { keyCode, modifiers in
                    if let message = settings.globalShortcutConflict(keyCode: keyCode, modifiers: modifiers) {
                        shortcutError = message
                        return false
                    }
                    settings.shortcutKeyCode = keyCode; settings.shortcutModifiers = modifiers; onShortcutChange()
                    shortcutError = nil
                    return true
                }
                Button("恢复为 ⌘⇧B") {
                    shortcutError = settings.resetShortcut()
                    if shortcutError == nil { onShortcutChange() }
                }
            }
            Section("快捷面板右键操作") {
                ForEach(QuickPanelAction.allCases) { action in
                    let shortcut = settings.quickShortcut(for: action)
                    HStack {
                        Text(action.title)
                        Spacer()
                        ShortcutRecorder(
                            keyCode: shortcut.keyCode,
                            modifiers: shortcut.modifiers,
                            allowsUnmodified: true
                        ) { keyCode, modifiers in
                            let message = settings.setQuickShortcut(
                                PassteShortcut(keyCode: keyCode, modifiers: modifiers),
                                for: action
                            )
                            shortcutError = message
                            return message == nil
                        }
                    }
                }
                Button("恢复右键操作默认快捷键") {
                    shortcutError = settings.resetQuickActionShortcuts()
                }
            }
            Section("固定导航快捷键") {
                LabeledContent("预览／关闭／资料库／设置", value: "Space／Esc／⌘L／⌘,")
                LabeledContent("快速粘贴前 9 项", value: "⌘1～⌘9")
            }
            if let shortcutError {
                Section {
                    Label(shortcutError, systemImage: "exclamationmark.triangle.fill")
                        .foregroundStyle(.red)
                }
            }
        }.formStyle(.grouped)
    }

    private var storage: some View {
        Form {
            Section("自动归档") {
                Text("超过 30 天或热数据超过 10,000 条时归档。收藏、置顶和普通分组内容不会自动归档。")
                Button("立即检查归档") { Task { await state.runArchive() } }.disabled(state.isBusy)
            }
            Section("本地备份") {
                HStack { Button("导出备份…", action: onExport); Button("导入备份…", action: onImport) }
                Text("备份包含 Passte 内保存的内容和元数据，不复制原始文件实体。")
            }
            if let message = state.statusMessage { Text(message).foregroundStyle(.secondary) }
        }.formStyle(.grouped)
    }

    private var advanced: some View {
        Form {
            Section("辅助功能") {
                LabeledContent("直接粘贴权限", value: pasteCoordinator.accessibilityTrusted() ? "已授权" : "未授权")
                Button("打开授权提示") { pasteCoordinator.requestAccessibilityPermission() }
                Text("未授权时，Passte 仍会把内容复制到剪贴板，并提示手动粘贴。")
            }
            Section("搜索索引") {
                Button("重建搜索索引") { Task { do { try await state.repository.rebuildSearchIndex(); state.presentStatus("搜索索引已重建") } catch { state.show(error) } } }
            }
        }.formStyle(.grouped)
    }

    private var about: some View {
        VStack(spacing: 16) {
            Image(systemName: "square.stack.3d.up.fill").font(.system(size: 64)).foregroundStyle(.purple)
            Text("Passte").font(.largeTitle.bold())
            Text("版本 0.1.0（Build 1）")
            Text("本地优先的 macOS 剪贴板资料库").foregroundStyle(.secondary)
            Text("Passte v0.1 不包含网络、AI 分析或云同步功能。").font(.caption).foregroundStyle(.secondary)
        }.frame(maxWidth: .infinity, maxHeight: .infinity)
    }

    private func updateLoginItem(_ enabled: Bool) {
        do {
            if enabled { try SMAppService.mainApp.register() } else { try SMAppService.mainApp.unregister() }
            loginEnabled = enabled
        } catch { state.show(error); loginEnabled = SMAppService.mainApp.status == .enabled }
    }
}

struct ShortcutRecorder: NSViewRepresentable {
    let keyCode: UInt32
    let modifiers: UInt32
    var allowsUnmodified = false
    let onChange: (UInt32, UInt32) -> Bool

    func makeNSView(context: Context) -> ShortcutRecorderNSView {
        ShortcutRecorderNSView(keyCode: keyCode, modifiers: modifiers, allowsUnmodified: allowsUnmodified, onChange: onChange)
    }
    func updateNSView(_ nsView: ShortcutRecorderNSView, context: Context) { nsView.update(keyCode: keyCode, modifiers: modifiers) }
}

final class ShortcutRecorderNSView: NSView {
    private var keyCode: UInt32
    private var modifiers: UInt32
    private let allowsUnmodified: Bool
    private let onChange: (UInt32, UInt32) -> Bool
    private var recording = false

    init(keyCode: UInt32, modifiers: UInt32, allowsUnmodified: Bool, onChange: @escaping (UInt32, UInt32) -> Bool) {
        self.keyCode = keyCode; self.modifiers = modifiers; self.allowsUnmodified = allowsUnmodified; self.onChange = onChange
        super.init(frame: NSRect(x: 0, y: 0, width: 220, height: 32))
        wantsLayer = true
    }
    required init?(coder: NSCoder) { fatalError() }
    override var acceptsFirstResponder: Bool { true }
    override var intrinsicContentSize: NSSize { NSSize(width: 220, height: 32) }
    override func mouseDown(with event: NSEvent) { recording = true; window?.makeFirstResponder(self); needsDisplay = true }
    override func keyDown(with event: NSEvent) {
        guard recording else { return }
        let flags = event.modifierFlags.intersection(.deviceIndependentFlagsMask)
        var carbon: UInt32 = 0
        if flags.contains(.command) { carbon |= UInt32(cmdKey) }
        if flags.contains(.shift) { carbon |= UInt32(shiftKey) }
        if flags.contains(.option) { carbon |= UInt32(optionKey) }
        if flags.contains(.control) { carbon |= UInt32(controlKey) }
        guard carbon != 0 || allowsUnmodified else { NSSound.beep(); return }
        let candidateKeyCode = UInt32(event.keyCode)
        guard onChange(candidateKeyCode, carbon) else {
            recording = false; NSSound.beep(); needsDisplay = true; return
        }
        keyCode = candidateKeyCode; modifiers = carbon; recording = false; needsDisplay = true
    }
    override func draw(_ dirtyRect: NSRect) {
        let rect = bounds.insetBy(dx: 0.5, dy: 0.5)
        let path = NSBezierPath(roundedRect: rect, xRadius: 7, yRadius: 7)
        (recording ? NSColor.controlAccentColor.withAlphaComponent(0.15) : NSColor.controlBackgroundColor).setFill(); path.fill()
        (recording ? NSColor.controlAccentColor : NSColor.separatorColor).setStroke(); path.stroke()
        let text = recording ? "请按新的快捷键…" : ShortcutFormatter.display(keyCode: keyCode, modifiers: modifiers)
        let attributes: [NSAttributedString.Key: Any] = [.font: NSFont.systemFont(ofSize: 13, weight: .medium), .foregroundColor: NSColor.labelColor]
        let size = text.size(withAttributes: attributes)
        text.draw(at: NSPoint(x: (bounds.width - size.width) / 2, y: (bounds.height - size.height) / 2), withAttributes: attributes)
    }
    func update(keyCode: UInt32, modifiers: UInt32) { self.keyCode = keyCode; self.modifiers = modifiers; needsDisplay = true }
}

enum ShortcutFormatter {
    static func display(keyCode: UInt32, modifiers: UInt32) -> String {
        var value = ""
        if modifiers & UInt32(controlKey) != 0 { value += "⌃" }
        if modifiers & UInt32(optionKey) != 0 { value += "⌥" }
        if modifiers & UInt32(shiftKey) != 0 { value += "⇧" }
        if modifiers & UInt32(cmdKey) != 0 { value += "⌘" }
        let names: [UInt32: String] = [
            0: "A", 1: "S", 2: "D", 3: "F", 4: "H", 5: "G", 6: "Z", 7: "X", 8: "C", 9: "V",
            11: "B", 12: "Q", 13: "W", 14: "E", 15: "R", 16: "Y", 17: "T", 18: "1", 19: "2",
            20: "3", 21: "4", 22: "6", 23: "5", 24: "=", 25: "9", 26: "7", 27: "-", 28: "8", 29: "0",
            30: "]", 31: "O", 32: "U", 33: "[", 34: "I", 35: "P", 36: "Return", 37: "L", 38: "J",
            39: "'", 40: "K", 41: ";", 42: "\\", 43: ",", 44: "/", 45: "N", 46: "M", 47: ".",
            48: "Tab", 49: "Space", 50: "`", 51: "⌫", 53: "Esc", 76: "Return"
        ]
        return value + (names[keyCode] ?? "Key \(keyCode)")
    }
}
