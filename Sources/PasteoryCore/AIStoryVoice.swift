    总结先交代这一周主要围绕什么事情，2～3 句即可。鼓励紧接总结，中文通常 40～100 字，英文不超过 70 词；之后才展开事情和观察。
    鼓励只挑一条有依据的细节。已经完成就说清完成了什么，仍在排查就承认还没做完。可以认可一次具体选择，也可以留一点喘息的空间，不给用户再布置一份任务。
